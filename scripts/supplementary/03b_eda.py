# 5. Variance decomposition: what is left after firm and year effects
VD = ["tesg", "e", "s", "g", "tesg_w", "e_w", "s_w", "g_w", "sa", "size_w", "age_w", "roa_w", "lev_w", "tq_w", "growth_w", "cash_w", "size_ln_w"]
tss = ((df[VD] - df[VD].mean()) ** 2).sum()
r_firm, r_both = resid(df[VD], D_FIRM), resid(df[VD], D_BOTH)
vd = pd.DataFrame({"sd_total": df[VD].std(),
                   "share_between_firm": 1 - (r_firm ** 2).sum(axis=0) / tss.values,
                   "share_year_given_firm": ((r_firm ** 2).sum(axis=0) - (r_both ** 2).sum(axis=0)) / tss.values,
                   "share_left_after_firm_year": (r_both ** 2).sum(axis=0) / tss.values,
                   "sd_left_after_firm_year": pd.DataFrame(r_both, columns=VD).std()})
section("5. Variance decomposition: shares of total variance", vd, name="eda_variance_decomposition",
        text="share_between_firm = R-squared of firm dummies; share_year_given_firm = extra R-squared from year dummies; "
             "share_left = what firm + year fixed effects cannot absorb (the variation the two-way FE estimator uses).")
