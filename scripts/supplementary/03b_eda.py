def md_table(d, index=True, digits=3):
    d = d.reset_index() if index else d
    f = d.copy()
    for c in f.columns:
        if pd.api.types.is_float_dtype(f[c]):
            f[c] = f[c].round(digits)
    lines = ["| " + " | ".join(map(str, f.columns)) + " |", "|" + "---|" * len(f.columns)]
    for row in f.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v).replace("|", "/") for v in row) + " |")
    return "\n".join(lines)


def section(title, d=None, text=None, name=None, index=True):
    print(f"\n=== {title} ===")
    report.extend([f"## {title}", ""])
    if text:
        print(text)
        report.extend([text, ""])
    if d is not None:
        print(d.round(3).to_string(index=index))
        report.extend([md_table(d, index=index), ""])
        if name:
            d.round(6).to_csv(OUT_T / f"{name}.csv", index=index, encoding="utf-8")


# projections on firm and year effects (numpy least squares on dummy matrices)
def dummies(cols):
    parts = [np.ones((len(df), 1))]
    for c in cols:
        d = pd.get_dummies(df[c].astype(str), drop_first=True, dtype=float).values
        parts.append(d)
    return np.hstack(parts)


D_FIRM, D_BOTH = dummies(["stock_code"]), dummies(["stock_code", "year"])


def resid(Y, D):
    Y = np.asarray(Y, dtype=float)
    beta, *_ = np.linalg.lstsq(D, Y, rcond=None)
    return Y - D @ beta


